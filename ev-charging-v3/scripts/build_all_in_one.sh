#!/usr/bin/env bash
# Regenerates database/00_install_all_in_one.sql from 01..04 so the two can never drift apart.
set -euo pipefail
D="$(cd "$(dirname "$0")/.." && pwd)/database"
{
  echo "-- ====================================================================="
  echo "-- 00_install_all_in_one.sql  (GENERATED by scripts/build_all_in_one.sh: 01_schema + 02_procedures + 03_views + 04_sample_data)"
  echo "-- Open this ONE file in MySQL Workbench and press the lightning button (or: mysql -u root -p < this file)."
  echo "-- It DROPS and recreates the database \`ev_charging\`. Do not run it on data you want to keep."
  echo "-- ====================================================================="
  echo "DROP DATABASE IF EXISTS ev_charging;"
  echo "CREATE DATABASE ev_charging CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
  echo "USE ev_charging;"
  for f in 01_schema 02_procedures 03_views 04_sample_data; do echo; cat "$D/$f.sql"; done
  echo
  echo "SELECT 'ev_charging database installed' AS result;"
} > "$D/00_install_all_in_one.sql"
echo "wrote $D/00_install_all_in_one.sql"
